select 
    o.*,
    c.customer_id,
    c.customer_type,
    c.dob,
    c.province,
    c.registration_channel,
    c.registration_date,
    p.category,
    p.brand,
    p.cogs,
    p.price,
    p.sku_name,
    p.product,
    p.variant,
    f.funnel_id,
    f.channel_source,
    f.event,
    f.status,
    f.funnel_date,
    t.transaction_date,
    t.payment_method,
    t.before_tax,
    t.tax,
    t.after_tax,
    t.shipping_cost,
    t.transaction_discount,
    t.total_paid,
    pa.payment_method,
    row_number() over (partition by o.transaction_id,o.order_id,o.customer_id,o.sku_id,o.sku_id) as rn
  from `Latihan.order_detail` as o left join `Latihan.customer_detail` as c on o.customer_id = c.customer_id left join `Latihan.product_detail` as p on o.sku_id = p.sku_id left join `Latihan.funnel_detail` as f on o.order_id = f.order_id left join `Latihan.transaction_detail` as t on o.transaction_id = t.transaction_id left join `Latihan.payment_detail` as pa on t.payment_method = pa.id